// Cover viewer: full-screen, hi-res where available. Wheel / pinch / + − zoom around the pointer,
// drag pans, double-click toggles 1× ↔ 2.5×, 0 or "fit" resets, Esc / × / click outside closes.
const ZV_MIN = 1, ZV_MAX = 6;
let zv = null;
function buildViewer() {
  const el = document.createElement('div');
  el.className = 'zv'; el.setAttribute('role', 'dialog'); el.setAttribute('aria-modal', 'true'); el.setAttribute('aria-label', 'Cover viewer');
  el.innerHTML = `<div class="zv-stage"><img class="zv-img" alt="" draggable="false" /></div>
    <div class="zv-bar"><button type="button" class="zv-btn" data-zv="out" aria-label="Zoom out">−</button><span class="zv-level">100%</span>
    <button type="button" class="zv-btn" data-zv="in" aria-label="Zoom in">+</button><button type="button" class="zv-btn zv-fit" data-zv="fit">fit</button></div>
    <button type="button" class="zv-close" aria-label="Close">×</button>`;
  document.body.appendChild(el);
  const v = { el, stage: el.querySelector('.zv-stage'), img: el.querySelector('.zv-img'), level: el.querySelector('.zv-level'), s: 1, x: 0, y: 0, pts: new Map(), moved: 0, last: null, pinch: null };
  const apply = () => {
    const bw = v.img.offsetWidth, bh = v.img.offsetHeight; // fitted size before scaling (transforms don't affect offset*)
    const mx = Math.max(0, (bw * v.s - window.innerWidth) / 2 + 40), my = Math.max(0, (bh * v.s - window.innerHeight) / 2 + 40);
    v.x = Math.max(-mx, Math.min(mx, v.x)); v.y = Math.max(-my, Math.min(my, v.y));
    if (v.s === 1) { v.x = 0; v.y = 0; }
    v.img.style.transform = `translate(${v.x}px,${v.y}px) scale(${v.s})`;
    v.level.textContent = Math.round(v.s * 100) + '%';
    el.classList.toggle('zoomed', v.s > 1);
  };
  // zoom to scale s2, keeping the point (cx, cy) (viewport coords) still
  v.zoomAt = (s2, cx = window.innerWidth / 2, cy = window.innerHeight / 2) => {
    s2 = Math.max(ZV_MIN, Math.min(ZV_MAX, s2));
    const ox = cx - window.innerWidth / 2, oy = cy - window.innerHeight / 2, k = s2 / v.s;
    v.x = ox - (ox - v.x) * k; v.y = oy - (oy - v.y) * k; v.s = s2; apply();
  };
  v.reset = () => { v.s = 1; v.x = 0; v.y = 0; apply(); };
  v.apply = apply;
  el.addEventListener('wheel', e => { e.preventDefault(); v.zoomAt(v.s * Math.exp(-e.deltaY * 0.0018), e.clientX, e.clientY); }, { passive: false });
  v.stage.addEventListener('pointerdown', e => {
    v.stage.setPointerCapture(e.pointerId); v.pts.set(e.pointerId, { x: e.clientX, y: e.clientY }); v.moved = 0;
    if (v.pts.size === 2) { const [a, b] = [...v.pts.values()]; v.pinch = { d: Math.hypot(a.x - b.x, a.y - b.y), s: v.s }; }
  });
  v.stage.addEventListener('pointermove', e => {
    if (!v.pts.has(e.pointerId)) return;
    const prev = v.pts.get(e.pointerId), cur = { x: e.clientX, y: e.clientY };
    v.pts.set(e.pointerId, cur);
    if (v.pts.size === 2 && v.pinch) {
      const [a, b] = [...v.pts.values()];
      v.zoomAt(v.pinch.s * Math.hypot(a.x - b.x, a.y - b.y) / v.pinch.d, (a.x + b.x) / 2, (a.y + b.y) / 2);
    } else if (v.pts.size === 1 && v.s > 1) {
      v.x += cur.x - prev.x; v.y += cur.y - prev.y; apply();
    }
    v.moved += Math.abs(cur.x - prev.x) + Math.abs(cur.y - prev.y);
  });
  const up = e => { v.pts.delete(e.pointerId); if (v.pts.size < 2) v.pinch = null; };
  v.stage.addEventListener('pointerup', up); v.stage.addEventListener('pointercancel', up);
  v.stage.addEventListener('dblclick', e => { e.preventDefault(); if (v.s > 1) v.reset(); else v.zoomAt(2.5, e.clientX, e.clientY); });
  // click on the backdrop (not the image, not after a drag) closes
  v.stage.addEventListener('click', e => { if (e.target === v.stage && v.moved < 4) closeCoverViewer(); });
  el.querySelector('.zv-close').addEventListener('click', closeCoverViewer);
  el.querySelector('.zv-bar').addEventListener('click', e => {
    const b = e.target.closest('[data-zv]'); if (!b) return;
    if (b.dataset.zv === 'in') v.zoomAt(v.s * 1.5); else if (b.dataset.zv === 'out') v.zoomAt(v.s / 1.5); else v.reset();
  });
  window.addEventListener('resize', () => { if (el.classList.contains('open')) apply(); });
  // capture phase so the page's own Escape handling (floating covers) doesn't also run
  window.addEventListener('keydown', e => {
    if (!el.classList.contains('open')) return;
    if (e.key === 'Escape') { e.stopImmediatePropagation(); closeCoverViewer(); }
    else if (e.key === '+' || e.key === '=') v.zoomAt(v.s * 1.5);
    else if (e.key === '-' || e.key === '_') v.zoomAt(v.s / 1.5);
    else if (e.key === '0') v.reset();
  }, true);
  return v;
}
let zvReturnFocus = null;
function openCoverViewer(rec, side) {
  const src = rec[side + 'Lg'] || rec[side];
  if (!src) return;
  zv = zv || buildViewer();
  zvReturnFocus = document.activeElement;
  zv.img.alt = `${rec.title}, ${side === 'back' ? 'back' : 'front'} cover`;
  zv.img.src = src;
  zv.reset();
  zv.el.classList.add('open');
  document.body.style.overflow = 'hidden';
  zv.el.querySelector('.zv-close').focus({ preventScroll: true });
}
function closeCoverViewer() {
  if (!zv) return;
  zv.el.classList.remove('open');
  document.body.style.overflow = '';
  if (zvReturnFocus && zvReturnFocus.focus) zvReturnFocus.focus({ preventScroll: true });
}
window.addEventListener('popstate', closeCoverViewer);

// Record page (#album/<id>). Called by app.js whenever the album page is shown.
window.renderAlbum = function(id) {
  const rec = byId(id);
  if (!rec) { App.showPage('film-photo', 'replace'); return; }
  shownRecId = rec.id;
  let n = 0;
  const facts = factsHTML(rec, ['artist', 'year', 'label', 'catno', 'country', 'style', 'media', 'matrix']);
  // Medley parts (B1.2, B1.3…) play as part of B1.1's file: not greyed when B1.1 is playable.
  const liveMedleys = new Set((rec.tracks || []).filter(t => t[3] && /\.1$/.test(t[0])).map(t => t[0].replace(/\.1$/, '')));
  const tracks = (rec.tracks || []).map(([pos, title, dur, url]) => {
    if (!url) {
      const inMedley = liveMedleys.has(String(pos).replace(/\.\d+$/, '')) && /\.\d+$/.test(pos);
      return `<li${inMedley ? '' : ' class="tr-off" title="Not available yet"'}><span class="tr-pos">${esc(pos)}</span><span class="tr-title">${esc(title)}</span><span class="tr-dur">${esc(dur)}</span></li>`;
    }
    const i = n++;
    return `<li data-i="${i}" data-pos="${esc(pos)}" data-dur="${esc(dur)}" data-title="${esc(title)}"><button type="button" class="tr-btn" aria-label="Play ${esc(title)}">`
      + `<span class="tr-pos">${esc(pos)}</span><span class="tr-title">${esc(title)}</span><span class="tr-dur">${esc(dur)}</span></button></li>`;
  }).join('');
  albumView.innerHTML = `
    <div class="album-meta">
      <p class="label-upper album-kicker">Nº ${esc(rec.num)}</p>
      <h1 class="album-title">${esc(rec.title)}</h1>
      <p class="album-artist">${esc(rec.artist)}</p>
      <dl class="album-facts">${facts}</dl>
    </div>
    ${rec.back ? `<button type="button" class="album-cover" aria-label="Flip cover" title="Click to flip · double-click to zoom">${cardHTML(rec, false)}</button>`
      : `<div class="album-cover album-cover--static" title="Double-click to zoom">${cardHTML(rec, false)}</div>`}
    ${tracks ? `<section class="album-section album-tracks" aria-label="Tracklist">
      <h2 class="label-upper">Tracklist</h2>
      <ol class="tracklist${n ? ' tracklist--playable' : ''}">${tracks}</ol>
    </section>` : ''}
    <section class="album-section album-article" aria-label="Article">
      <h2 class="label-upper">Article</h2>
      ${rec.article || '<p class="album-empty">An article about the artist and this release is on its way.</p>'}
    </section>`;
  // Cover: single click flips (when there is a back), double-click opens the zoomable viewer on the side showing.
  const cover = albumView.querySelector('.album-cover');
  if (cover) {
    let flipTimer = null;
    if (rec.back) cover.addEventListener('click', e => {
      if (e.detail > 1) return;
      clearTimeout(flipTimer); flipTimer = setTimeout(() => cover.classList.toggle('flipped'), 230);
    });
    cover.addEventListener('dblclick', e => {
      e.preventDefault(); clearTimeout(flipTimer);
      openCoverViewer(rec, cover.classList.contains('flipped') ? 'back' : 'front');
    });
  }
  document.title = `${rec.title} — MusicaNossa`;
  markRows(); // reflect the site-wide player if this record is the one playing
};
