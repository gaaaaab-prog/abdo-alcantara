(function() {
'use strict';
// Record archive (the Acervo page). Physics and styling are unchanged from the photo version;
// each floating item is now a square record cover that flips to its reverse side when enlarged.
const PHOTO_FRICTION = 0.9917, PHOTO_DRIFT = 0.00184, PHOTO_MAX_SPEED = 2.3;
const THUMB_HEIGHT = 72, COLLISION_BUFFER = 20, COLLISION_FORCE = 0.03;
// Desktop (wider than the 900px breakpoint) shows the floating covers 10% larger.
const DESKTOP_MQ = window.matchMedia('(min-width: 901px)');
const thumbSize = () => Math.round(THUMB_HEIGHT * (DESKTOP_MQ.matches ? 1.1 : 1));
const ENLARGE_FRACTION = 0.34, ENLARGE_MIN = 180, ENLARGE_MAX = 300; // "slightly" enlarged square
const INFO_GAP = 32, INFO_MIN_W = 200, INFO_MAX_W = 260; // details panel beside the enlarged cover
const PHOTO_CONFIG = { friction: PHOTO_FRICTION, drift: PHOTO_DRIFT, maxSpeed: PHOTO_MAX_SPEED, centerY: 0.42 };

// Single source of truth: window.ARCHIVE_DATA from js/archive-data.js, generated by
// Recordings/_musicanossa/build_archive.py from each record folder (record.json + discogs.json).
// front/back = 600px covers, frontSm/backSm = 160px card versions ('' = no image yet).
const ARCHIVE = Array.isArray(window.ARCHIVE_DATA) ? window.ARCHIVE_DATA : [];
const byId = id => ARCHIVE.find(r => r.id === id) || null;

const photoContainer = document.getElementById('photo-float-container');
const listEl = document.getElementById('archive-list');
const albumView = document.getElementById('album-view');

function esc(s) { return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])); }
// small = true for the floating 72px cards: load the 160px file, keep the 600px one in data-full.
function face(rec, side, small) {
  const full = rec[side], sm = rec[side + 'Sm'];
  if (full) {
    const src = small && sm ? sm : full;
    return `<div class="record-face record-${side}"><img src="${esc(src)}"${small && sm ? ` data-full="${esc(full)}"` : ''} alt="${esc(rec.title)}, ${side === 'front' ? 'front' : 'back'} cover" loading="lazy" decoding="async" /></div>`;
  }
  return `<div class="record-face record-${side}"></div>`;
}
// Only records with both sides get a reverse face (and the flip); the rest just show the front.
function cardHTML(rec, small) {
  return `<div class="record-inner">${face(rec, 'front', small)}${rec.back ? face(rec, 'back', small) : ''}</div>`;
}
function factsHTML(rec, keys) {
  const matrix = Object.entries(rec.matrix || {}).map(([side, m]) => `${side}: ${m}`).join(' / ');
  const all = { artist: ['Artist', rec.artist], year: ['Year', rec.year], label: ['Label', rec.label], catno: ['Cat. Nº', rec.catno],
    country: ['Country', rec.country], style: ['Style', rec.style], media: ['Media', rec.media], matrix: ['Matrix', matrix] };
  return keys.filter(k => k !== 'matrix' || matrix)
    .map(k => `<div><dt class="label-upper">${all[k][0]}</dt><dd>${esc(all[k][1] || '—')}</dd></div>`).join('');
}
// Details shown to the left of an enlarged cover (above it on narrow screens).
let infoEl = null;
function showInfo(rec) {
  if (!infoEl) return;
  infoEl.innerHTML = `<p class="label-upper ri-num">Nº ${esc(rec.num)}</p><p class="ri-title">${esc(rec.title)}</p><p class="ri-artist">${esc(rec.artist)}</p>
    <dl class="ri-facts">${factsHTML(rec, ['year', 'label', 'catno', 'country', 'style', 'media'])}</dl>`;
  infoEl.classList.add('visible');
}
function hideInfo() { if (infoEl) infoEl.classList.remove('visible'); }
function openAlbum(id) { App.showPage('album', 'push', id); }

class FloatingImage {
  constructor(el, x, y, angle, rec) {
    this.el = el; this.x = x; this.y = y; this.rec = rec;
    const t = thumbSize();
    this.ar = 1; this.h = t; this.w = t;
    el.style.width = `${t}px`; el.style.height = `${t}px`;
    this._driftAngle = angle;
    this._driftAngleSpeed = (Math.random() < 0.5 ? 1 : -1) * (0.0003 + Math.random() * 0.0005);
    this.vx = 0; this.vy = 0;
    this._enlarged = false;
    el.style.transform = `translate3d(${x}px,${y}px,0)`;
    // First click: enlarge + flip to the reverse side. Click again: open the record's page.
    el.addEventListener('click', e => { e.stopPropagation(); if (this._enlarged) openAlbum(rec.id); else this.toggleEnlarge(); });
  }
  measure() { this.w = this.el.offsetWidth; this.h = this.el.offsetHeight; }
  _shrink(fi) {
    fi._enlarged = false; fi.el.style.transition = 'none'; fi.el.classList.remove('enlarged');
    const t = thumbSize();
    fi.w = t; fi.h = t;
    fi.el.style.width = `${t}px`; fi.el.style.height = `${t}px`;
    requestAnimationFrame(() => { fi.el.style.transition = ''; });
  }
  toggleEnlarge() {
    if (this._enlarged) {
      this._shrink(this); this.el.style.left = ''; this.el.style.top = '';
      this.el.style.transform = `translate3d(${this.x}px,${this.y}px,0)`;
      photoContainer.classList.remove('has-enlarged'); hideInfo(); return;
    }
    window.floatingImages.forEach(fi => { if (fi._enlarged) this._shrink(fi); });
    this._enlarged = true; this.el.style.transition = 'none'; this.el.classList.add('enlarged');
    showInfo(this.rec);
    this._layout();
    this.el.querySelectorAll('img[data-full]').forEach(img => { img.src = img.dataset.full; img.removeAttribute('data-full'); });
    this.el.style.transform = 'none';
    photoContainer.classList.add('has-enlarged');
  }
  // Size and place the enlarged record for the current viewport (also re-run on resize):
  // details on the left and cover on the right, centred as a pair; on narrow screens the
  // details sit above the cover.
  _layout() {
    const W = window.innerWidth, H = window.innerHeight;
    const s = Math.round(Math.max(ENLARGE_MIN, Math.min(ENLARGE_MAX, Math.min(W, H) * ENLARGE_FRACTION)));
    let left = Math.round((W - s) / 2), top = Math.round((H - s) / 2);
    if (infoEl) {
      const side = W >= s + INFO_GAP + INFO_MIN_W + 48;
      infoEl.classList.toggle('stacked', !side);
      if (side) {
        const pw = Math.min(INFO_MAX_W, W - s - INFO_GAP - 48), x0 = Math.round((W - (pw + INFO_GAP + s)) / 2);
        left = x0 + pw + INFO_GAP;
        infoEl.style.width = `${pw}px`; infoEl.style.left = `${x0}px`;
        infoEl.style.top = `${Math.max(16, Math.round(top + (s - infoEl.offsetHeight) / 2))}px`;
      } else {
        infoEl.style.width = `${s}px`; infoEl.style.left = `${left}px`;
        const ih = infoEl.offsetHeight;
        top = Math.round(Math.max(72 + ih + 16, (H - (ih + 16 + s)) / 2 + ih + 16));
        infoEl.style.top = `${top - 16 - ih}px`;
      }
    }
    this.el.style.width = `${s}px`; this.el.style.height = `${s}px`;
    this.el.style.left = `${left}px`; this.el.style.top = `${top}px`;
  }
  tick() {
    if (this._enlarged || this.el.style.opacity === '0') return;
    App.tickEntity(this, PHOTO_CONFIG);
  }
}
window.floatingImages = [];
window.addEventListener('resize', () => window.floatingImages.forEach(fi => { if (fi._enlarged) fi._layout(); }));
DESKTOP_MQ.addEventListener('change', () => {
  const t = thumbSize();
  window.floatingImages.forEach(fi => { if (!fi._enlarged) { fi.w = t; fi.h = t; fi.el.style.width = `${t}px`; fi.el.style.height = `${t}px`; } });
});
let collisionTickRegistered = false, collisionFrame = 0;
function photoCollisionTick() {
  const imgs = window.floatingImages;
  if (!imgs.length) return;
  for (let i = 0; i < imgs.length; i++) imgs[i].tick();
  if (++collisionFrame & 1) {
    for (let i = 0; i < imgs.length; i++) {
      const a = imgs[i];
      if (a._enlarged || a.el.style.opacity === '0') continue;
      for (let j = i + 1; j < imgs.length; j++) {
        const b = imgs[j];
        if (b._enlarged || b.el.style.opacity === '0') continue;
        const dx = (b.x + b.w * 0.5) - (a.x + a.w * 0.5), dy = (b.y + b.h * 0.5) - (a.y + a.h * 0.5);
        const dSq = dx * dx + dy * dy, md = (a.w + b.w) * 0.5 + COLLISION_BUFFER;
        if (dSq < md * md) {
          const d = Math.sqrt(dSq) || 1, nx = dx / d, ny = dy / d;
          const f = COLLISION_FORCE * (1 - d / md);
          a.vx -= nx * f; a.vy -= ny * f; b.vx += nx * f; b.vy += ny * f;
        }
      }
    }
  }
}
window.initPhotoFloat = function() {
  window.destroyPhotoFloat();
  if (!photoContainer) return;
  infoEl = document.createElement('div');
  infoEl.className = 'record-info';
  photoContainer.appendChild(infoEl);
  const base = Math.random() * Math.PI * 2, count = ARCHIVE.length;
  for (let i = 0; i < count; i++) {
    const rec = ARCHIVE[i], el = document.createElement('div');
    el.className = rec.back ? 'float-img record has-back' : 'float-img record';
    el.dataset.id = rec.id;
    el.setAttribute('role', 'button');
    el.setAttribute('aria-label', `${rec.title} — ${rec.artist}`);
    el.innerHTML = cardHTML(rec, true) + '<span class="record-hint" aria-hidden="true">Open →</span>';
    photoContainer.appendChild(el);
    const angle = base + (i / count) * Math.PI * 2;
    const margin = 160, rx = margin + Math.random() * Math.max(0, window.innerWidth - margin * 2), ry = margin + Math.random() * Math.max(0, window.innerHeight - 260 - margin);
    window.floatingImages.push(new FloatingImage(el, rx, ry, angle, rec));
  }
  setTimeout(() => window.floatingImages.forEach(fi => fi.measure()), 100);
  if (!collisionTickRegistered) { App.registerTick(photoCollisionTick); collisionTickRegistered = true; }
};
window.destroyPhotoFloat = function() {
  if (photoContainer) { photoContainer.innerHTML = ''; photoContainer.classList.remove('has-enlarged'); }
  infoEl = null;
  window.floatingImages = [];
  if (collisionTickRegistered) { App.unregisterTick(photoCollisionTick); collisionTickRegistered = false; }
  collisionFrame = 0;
};

// List view under the floating layer (same records; keyboard/screen-reader friendly way in).
if (listEl) {
  listEl.replaceChildren(...ARCHIVE.map(rec => {
    const b = document.createElement('button');
    b.type = 'button'; b.className = 'music-entry'; b.dataset.id = rec.id;
    b.innerHTML = `<span class="me-num">${esc(rec.num)}</span><span class="me-title">${esc(rec.title)} <span class="me-artist">${esc(rec.artist)}</span></span><span class="me-meta">${esc([rec.media, rec.year].filter(Boolean).join(' · ') || '—')}</span>`;
    return b;
  }));
  listEl.addEventListener('click', e => { const b = e.target.closest('[data-id]'); if (b) openAlbum(b.dataset.id); });
}

// Tracklist player: one shared <audio> for the record page. A track is playable when the build
// gave it a URL (4th item); clicking its title plays it, clicking again pauses, the next one follows.
const player = new Audio();
player.preload = 'none';
let playable = [], current = -1;
const mmss = s => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
function rowEls() { return albumView.querySelectorAll('.tracklist li[data-i]'); }
function markRows() {
  rowEls().forEach(li => {
    const i = +li.dataset.i, on = i === current, btn = li.querySelector('.tr-btn');
    li.classList.toggle('playing', on && !player.paused);
    li.classList.toggle('current', on);
    li.querySelector('.tr-pos').textContent = on ? (player.paused ? '▶' : '❚❚') : li.dataset.pos;
    li.querySelector('.tr-dur').textContent = on && player.currentTime > 0 ? mmss(player.currentTime) : li.dataset.dur;
    btn.setAttribute('aria-label', `${on && !player.paused ? 'Pause' : 'Play'} ${li.dataset.title}`);
  });
}
function playAt(i) {
  if (i < 0 || i >= playable.length) { stopTracks(); return; }
  current = i;
  player.src = playable[i];
  player.play().then(markRows, markRows);
  markRows();
}
function stopTracks() {
  player.pause(); player.removeAttribute('src'); player.load();
  current = -1; markRows();
}
player.addEventListener('play', markRows);
player.addEventListener('pause', markRows);
player.addEventListener('timeupdate', () => { const li = albumView.querySelector(`.tracklist li[data-i="${current}"] .tr-dur`); if (li) li.textContent = mmss(player.currentTime); });
player.addEventListener('ended', () => playAt(current + 1));
player.addEventListener('error', () => {
  if (current < 0 || !player.getAttribute('src')) return;
  const li = albumView.querySelector(`.tracklist li[data-i="${current}"]`);
  if (li) li.classList.add('unavailable');
  playAt(current + 1);
});
albumView.addEventListener('click', e => {
  const btn = e.target.closest('.tr-btn');
  if (!btn) return;
  const i = +btn.closest('li').dataset.i;
  if (i === current) { if (player.paused) player.play().then(markRows, markRows); else player.pause(); }
  else playAt(i);
});
// Stop the music when the record page is left (any route: Back, nav, brand, menu).
const albumPage = document.getElementById('page-album');
if (albumPage) new MutationObserver(() => { if (!albumPage.classList.contains('active') && current >= 0) stopTracks(); })
  .observe(albumPage, { attributes: true, attributeFilter: ['class'] });

// Record page (#album/<id>). Called by app.js whenever the album page is shown.
window.renderAlbum = function(id) {
  const rec = byId(id);
  if (!rec) { App.showPage('film-photo', 'replace'); return; }
  if (current >= 0) stopTracks();
  playable = [];
  const facts = factsHTML(rec, ['artist', 'year', 'label', 'catno', 'country', 'style', 'media', 'matrix']);
  const tracks = (rec.tracks || []).map(([pos, title, dur, url]) => {
    if (!url) return `<li><span class="tr-pos">${esc(pos)}</span><span class="tr-title">${esc(title)}</span><span class="tr-dur">${esc(dur)}</span></li>`;
    const i = playable.push(url) - 1;
    return `<li data-i="${i}" data-pos="${esc(pos)}" data-dur="${esc(dur)}" data-title="${esc(title)}"><button type="button" class="tr-btn" aria-label="Play ${esc(title)}">`
      + `<span class="tr-pos">${esc(pos)}</span><span class="tr-title">${esc(title)}</span><span class="tr-dur">${esc(dur)}</span></button></li>`;
  }).join('');
  albumView.innerHTML = `
    <div class="album-meta">
      <p class="label-upper album-kicker">Nº ${esc(rec.num)}</p>
      <h1 class="album-title">${esc(rec.title)}</h1>
      <p class="album-artist">${esc(rec.artist)}</p>
      <dl class="album-facts">${facts}</dl>
    </div>
    ${rec.back ? `<button type="button" class="album-cover" aria-label="Flip cover">${cardHTML(rec, false)}</button>`
      : `<div class="album-cover album-cover--static">${cardHTML(rec, false)}</div>`}
    ${tracks ? `<section class="album-section album-tracks" aria-label="Tracklist">
      <h2 class="label-upper">Tracklist</h2>
      <ol class="tracklist${playable.length ? ' tracklist--playable' : ''}">${tracks}</ol>
    </section>` : ''}
    <section class="album-section album-article" aria-label="Article">
      <h2 class="label-upper">Article</h2>
      ${rec.article || '<p class="album-empty">An article about the artist and this release is on its way.</p>'}
    </section>`;
  const flip = albumView.querySelector('button.album-cover');
  if (flip) flip.addEventListener('click', e => e.currentTarget.classList.toggle('flipped'));
  document.title = `${rec.title} — MusicaNossa`;
};
const albumBack = document.getElementById('album-back');
if (albumBack) albumBack.addEventListener('click', () => App.showPage('film-photo'));

// Self-init: app.js runs before this script, so a page loaded directly on #film-photo or
// #album/<id> needs initialising here.
if (document.getElementById('page-film-photo')?.classList.contains('active')) window.initPhotoFloat();
if (document.getElementById('page-album')?.classList.contains('active')) window.renderAlbum(location.hash.split('/')[1] || '');
})();
