DESKTOP_MQ.addEventListener('change', () => {
  const t = thumbSize();
  window.floatingImages.forEach(fi => { if (!fi._enlarged) { fi.w = t; fi.h = t; fi.el.style.width = `${t}px`; fi.el.style.height = `${t}px`; } });
});
let collisionTickRegistered = false, collisionFrame = 0;
// Word rectangles the covers keep clear of; re-measured every AVOID_REFRESH frames (cheap, and follows
// filter collapse, resizes and the title fading in on scroll).
let avoidRects = [];
function measureAvoidRects() {
  const out = [];
  const add = el => {
    if (!el || !el.offsetParent && getComputedStyle(el).position !== 'fixed') return;
    const r = el.getBoundingClientRect();
    if (r.width && r.height && r.bottom > 0 && r.top < window.innerHeight) out.push(r);
  };
  // The filter rows count as one block, so a cover leaving one row isn't steered into the other.
  if (filtersEl && filtersEl.classList.contains('visible')) {
    const rows = [];
    filtersEl.querySelectorAll('.af-group').forEach(g => { const r = g.getBoundingClientRect(); if (r.width && r.height) rows.push(r); });
    if (rows.length) out.push({ left: Math.min(...rows.map(r => r.left)), right: Math.max(...rows.map(r => r.right)),
      top: Math.min(...rows.map(r => r.top)), bottom: Math.max(...rows.map(r => r.bottom)) });
  }
  add(document.querySelector('.site-brand'));
  if (document.body.classList.contains('scrolled')) document.querySelectorAll('#page-film-photo .hero-name, #page-film-photo .hero-tagline').forEach(add);
  avoidRects = out;
}
function avoidWords(fi) {
  for (const r of avoidRects) {
    const l = (fi.x + fi.w) - (r.left - AVOID_PAD), rt = (r.right + AVOID_PAD) - fi.x;
    const u = (fi.y + fi.h) - (r.top - AVOID_PAD), d = (r.bottom + AVOID_PAD) - fi.y;
    if (l <= 0 || rt <= 0 || u <= 0 || d <= 0) continue;
    // Leave by the shortest way out that has room for the cover (not into the screen edge),
    // with a force that grows with how far the cover is in.
    const VW = window.innerWidth, VH = window.innerHeight, P = AVOID_PAD, E = 18;
    const ways = [[l, -1, 0, r.left - P - E >= fi.w], [rt, 1, 0, VW - E - r.right - P >= fi.w],
      [u, 0, -1, r.top - P - E >= fi.h], [d, 0, 1, VH - 130 - r.bottom - P >= fi.h]].filter(w => w[3]);
    if (!ways.length) continue;
    const [m, sx, sy] = ways.reduce((a, b) => (b[0] < a[0] ? b : a));
    const f = AVOID_FORCE * Math.min(m, AVOID_RAMP) / AVOID_RAMP;
    fi.vx += sx * f; fi.vy += sy * f;
  }
}
function photoCollisionTick() {
  const imgs = window.floatingImages;
  if (!imgs.length) return;
  for (let i = 0; i < imgs.length; i++) imgs[i].tick();
  if (collisionFrame % AVOID_REFRESH === 0) measureAvoidRects();
  if (++collisionFrame & 1) {
    if (avoidRects.length) for (let i = 0; i < imgs.length; i++) {
      const a = imgs[i];
      if (!a._enlarged && a.el.style.opacity !== '0') avoidWords(a);
    }
    for (let i = 0; i < imgs.length; i++) {
      const a = imgs[i];
      if (a._enlarged || a.el.style.opacity === '0') continue;
      for (let j = i + 1; j < imgs.length; j++) {
        const b = imgs[j];
        if (b._enlarged || b.el.style.opacity === '0') continue;
        const dx = (b.x + b.w * 0.5) - (a.x + a.w * 0.5), dy = (b.y + b.h * 0.5) - (a.y + a.h * 0.5);
        const dSq = dx * dx + dy * dy, md = (a.w + b.w) * 0.5 + COLLISION_BUFFER;
        if (dSq < md * md) {
          const d = Math.sqrt(dSq) || 1, nx = dx / d, ny = dy / d;
          const f = COLLISION_FORCE * (1 - d / md);
          a.vx -= nx * f; a.vy -= ny * f; b.vx += nx * f; b.vy += ny * f;
        }
      }
    }
  }
}
window.initPhotoFloat = function() {
  window.destroyPhotoFloat();
  if (!photoContainer) return;
  infoEl = document.createElement('div');
  infoEl.className = 'record-info';
  photoContainer.appendChild(infoEl);
  const base = Math.random() * Math.PI * 2, count = ARCHIVE.length;
  for (let i = 0; i < count; i++) {
    const rec = ARCHIVE[i], el = document.createElement('div');
    el.className = rec.back ? 'float-img record has-back' : 'float-img record';
    el.dataset.id = rec.id;
    el.setAttribute('role', 'button');
    el.setAttribute('aria-label', `${rec.title} — ${rec.artist}`);
    el.innerHTML = cardHTML(rec, true) + '<span class="record-hint" aria-hidden="true">Open →</span>';
    photoContainer.appendChild(el);
    const angle = base + (i / count) * Math.PI * 2;
    const margin = 160, rx = margin + Math.random() * Math.max(0, window.innerWidth - margin * 2), ry = margin + Math.random() * Math.max(0, window.innerHeight - 260 - margin);
    window.floatingImages.push(new FloatingImage(el, rx, ry, angle, rec));
  }
  setTimeout(() => window.floatingImages.forEach(fi => fi.measure()), 100);
  applyFilters();
  if (!collisionTickRegistered) { App.registerTick(photoCollisionTick); collisionTickRegistered = true; }
};
window.destroyPhotoFloat = function() {
  if (photoContainer) { photoContainer.innerHTML = ''; photoContainer.classList.remove('has-enlarged'); }
  infoEl = null;
  window.floatingImages = [];
  if (collisionTickRegistered) { App.unregisterTick(photoCollisionTick); collisionTickRegistered = false; }
  collisionFrame = 0; avoidRects = [];
};

// Filters: two rows of text links (format, style). A record shows when it matches every active
// filter; clicking the active link again clears it. Filtered-out covers fade out and leave the physics
// (tick/collisions skip opacity 0); list rows are hidden.
const FILTERS = [['format', ['LP', '7" Single']], ['style', ['jazz', 'MPB', 'bossa', 'samba', 'forró']]];
const activeFilter = { format: null, style: null };
// Clicking a group's word (format / style) folds its links away; a folded group still shows its active value.
const collapsed = { format: false, style: false };
const recTags = (rec, group) => group === 'format' ? (rec.formats || (rec.media ? [rec.media] : [])) : (rec.styles || []);
const matchesFilters = rec => FILTERS.every(([g]) => !activeFilter[g] || recTags(rec, g).includes(activeFilter[g]));
const filtersEl = document.getElementById('photo-tabs');
function renderFilters() {
  if (!filtersEl) return;
  filtersEl.hidden = false;
  filtersEl.innerHTML = FILTERS.map(([g, values]) => {
    const shut = collapsed[g], shown = shut ? values.filter(v => activeFilter[g] === v) : values;
    return `<div class="af-group af-group--${g}${shut ? ' collapsed' : ''}"><button type="button" class="af-label" data-toggle="${g}" aria-expanded="${!shut}" title="${shut ? 'Show' : 'Hide'} ${g}">${g}</button>`
    + shown.map(v => {
      const n = ARCHIVE.filter(r => recTags(r, g).includes(v)).length, on = activeFilter[g] === v;
      return `<button type="button" class="af-link${on ? ' active' : ''}" data-group="${g}" data-value="${esc(v)}" aria-pressed="${on}"${n ? '' : ' disabled title="Nothing here yet"'}>${esc(v)}</button>`;
    }).join('<span class="af-sep" aria-hidden="true">·</span>') + '</div>';
  }).join('');
}
function applyFilters() {
  window.floatingImages.forEach(fi => {
    const on = matchesFilters(fi.rec);
    if (!on && fi._enlarged) fi.toggleEnlarge();
    fi.el.style.opacity = on ? '' : '0';
    fi.el.classList.toggle('filtered-out', !on);
    fi.el.setAttribute('aria-hidden', String(!on));
  });
  if (listEl) listEl.querySelectorAll('[data-id]').forEach(b => { b.hidden = !matchesFilters(byId(b.dataset.id)); });
}
if (filtersEl) {
  renderFilters();
  filtersEl.addEventListener('click', e => {
    const t = e.target.closest('.af-label');
    if (t) {
      e.stopPropagation();
      const g = t.dataset.toggle;
      collapsed[g] = !collapsed[g];
      renderFilters();
      const again = filtersEl.querySelector(`[data-toggle="${g}"]`);
      if (again) again.focus({ preventScroll: true });
      measureAvoidRects();
      return;
    }
    const a = e.target.closest('.af-link');
    if (!a || a.disabled) return;
    e.stopPropagation();
    const g = a.dataset.group, v = a.dataset.value;
    activeFilter[g] = activeFilter[g] === v ? null : v;
    renderFilters(); applyFilters();
  });
}

